FOLLOWUP_TIMEOUT_SECONDS = 40.0

#: 템플릿 매칭 임계값(mAuto 의 같은 대상과 동일).
FOLLOWUP_MATCH_THRESHOLD = 0.8

#: 그림을 처음 발견한 뒤 이만큼 기다렸다가 누른다(초). 뜬 직후에는 화면이 아직
#: 자리 잡는 중이라 입력이 안 먹거나 엉뚱하게 들어갈 수 있다(사용자 실측 요구).
